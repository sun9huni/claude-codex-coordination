#!/usr/bin/env bash
# Generate a handoff snapshot so the next agent (Claude / Codex / Cursor /
# human) can take over without trusting chat history.
#
# Usage: ./scripts/handoff.sh <next-agent> [<slice>]
#        ./scripts/handoff.sh --release <slice>   (or -r <slice>)
#   next-agent: free-form label, e.g. claude, codex, cursor, human
#   slice:      OPTIONAL. When present, run in per-slice mode: claim/refresh
#               ONLY .agent/status/<slice>.md (owner fields + heartbeat +
#               version bump), preserving its remaining_actions /
#               contract_pointers / body verbatim. CURRENT.md is left alone
#               (it becomes a derived index, regenerated by status.sh). When
#               absent, behavior is unchanged: bump CURRENT.md + snapshot.
#   --release:  Release the named slice. Clears owner_session / owner_label /
#               heartbeat to empty strings, sets state: released, bumps
#               version, refreshes last_updated. Preserves owner_agent,
#               remaining_actions, contract_pointers, and body verbatim.
#               Idempotent: re-running on an already-released slice just
#               bumps version + last_updated.
#
# Env seams (default = repo's own .agent, so today's behavior is identical):
#   AGENT_ROOT     Path to the .agent tree to operate on (handoffs/, status/).
#                  Default (unset) = "$ROOT/.agent".
#   OWNER_SESSION  Slice mode only: session id to record as owner_session.
#                  Default = a freshly generated UUID.
#   OWNER_LABEL    Slice mode only: free-form owner_label (may be empty).
#
# Concurrency model:
#   - Acquires an exclusive lock on .agent/handoffs/OWNER.lock for the
#     duration of the run so two handoffs cannot interleave snapshots.
#     Uses `flock` when available (Linux) and falls back to atomic
#     `mkdir` of OWNER.lock.d (macOS/*BSD/anywhere).
#   - Increments .agent/handoffs/CURRENT.md frontmatter `version` (used
#     by Stop hook to detect "agent forgot to update CURRENT.md").
#   - Writes a fresh snapshot under .agent/handoffs/state/sessions/
#     <YYYY-MM-DD-HHMMSS-UTC>-<agent>/ and re-points the symlink
#     .agent/handoffs/state/latest at it.
#   - CURRENT.md edits use a .tmp + atomic rename (mv -f) helper at
#     scripts/_atomic_write_current.sh — agents should call that, or
#     just use the Edit tool while holding the lock.
#
# Files written under state/sessions/<run>/:
#   git-status.txt      `git status --short` (empty if not a git repo)
#   git-log.txt         last 10 commits, oneline
#   diff.patch          working tree vs HEAD
#   diff-staged.patch   staged diff
#   meta.txt            timestamp, agent, version, host, root
#
# Does NOT auto-edit CURRENT.md beyond bumping the `version` field.
# The outgoing agent fills in the rest by hand (or via /handoff).

set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "usage: $0 <next-agent> [<slice>]" >&2
  echo "       $0 --release <slice>" >&2
  exit 2
fi

# Parse pre-positional flags: --release / -r and --no-auto-commit. Both
# must appear BEFORE the positional args. Order between the two flags
# does not matter.
RELEASE_MODE=0
NO_AUTO_COMMIT=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --release|-r)
      RELEASE_MODE=1
      shift
      ;;
    --no-auto-commit)
      NO_AUTO_COMMIT=1
      shift
      ;;
    *)
      break
      ;;
  esac
done
if [ "$RELEASE_MODE" -eq 1 ]; then
  if [ "$#" -lt 1 ] || [ -z "${1:-}" ]; then
    echo "usage: $0 --release <slice>" >&2
    exit 2
  fi
fi
if [ "$#" -lt 1 ]; then
  echo "usage: $0 <next-agent> [<slice>]" >&2
  echo "       $0 --release <slice>" >&2
  exit 2
fi

NEXT_AGENT="$1"
SLICE="${2:-}"
if [ "$RELEASE_MODE" -eq 1 ]; then
  # In release mode, $1 IS the slice (we shifted off --release).
  SLICE="$1"
fi
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# AGENT_ROOT seam: all .agent reads/writes go under $AGENT_DIR. Default
# (unset) = the repo's own .agent, so behavior is identical to before.
# ROOT (script location) stays as-is for locating the repo for git ops.
AGENT_DIR="${AGENT_ROOT:-$ROOT/.agent}"
HANDOFF_DIR="$AGENT_DIR/handoffs"
STATE_DIR="$HANDOFF_DIR/state"
SESSIONS_DIR="$STATE_DIR/sessions"
STATUS_DIR="$AGENT_DIR/status"
LOCK_FILE="$HANDOFF_DIR/OWNER.lock"
LOCK_DIR="$HANDOFF_DIR/OWNER.lock.d"
CURRENT="$HANDOFF_DIR/CURRENT.md"

mkdir -p "$HANDOFF_DIR"

# ─────────────────────────────────────────────────────────────────────────────
# slice_auto_commit: after a slice frontmatter write, auto-commit any
# untracked .agent/contracts/<slice>-* or .agent/plans/<slice>-* files.
# Skips (never fails) if any tracked-mod is present (other than the slice's
# own baton .agent/status/<slice>.md, which handoff.sh always rewrites),
# if any non-matching untracked file is present, or if --no-auto-commit
# was passed. Single `git status --porcelain` invocation. Called from
# both the claim path and the release path while the lock is still held.
# ─────────────────────────────────────────────────────────────────────────────
slice_auto_commit() {
  if [ "$NO_AUTO_COMMIT" -eq 1 ]; then
    echo "[handoff] auto-commit SKIPPED: --no-auto-commit" >&2
    return 0
  fi
  if [ -z "${SLICE:-}" ]; then
    return 0
  fi
  # Auto-commit operates on the workspace containing AGENT_DIR (so the
  # test harness, which sets AGENT_ROOT=<tmp>/.agent and cds into <tmp>,
  # commits into <tmp>'s git repo — not the script's $ROOT).
  local ws_root
  ws_root="$(dirname "$AGENT_DIR")"
  if ! git -C "$ws_root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    return 0
  fi

  local baton_path=".agent/status/$SLICE.md"
  local contracts_prefix=".agent/contracts/$SLICE-"
  local plans_prefix=".agent/plans/$SLICE-"
  # --untracked-files=all expands untracked dirs into their files so
  # the per-file prefix check actually sees `.agent/contracts/<slice>-…`
  # instead of a collapsed `.agent/contracts/` entry.
  local porcelain
  if ! porcelain="$(git -C "$ws_root" status --porcelain --untracked-files=all 2>/dev/null)"; then
    return 0
  fi

  # Dirty-tree policy:
  #   - TRACKED modifications (M/A/D/R/C/U etc.) BLOCK the auto-commit,
  #     EXCEPT for the slice's own baton — handoff.sh is allowed to
  #     rewrite that file as part of this run.
  #   - UNTRACKED files matching the slice's contracts/plans prefix are
  #     collected for the commit.
  #   - UNTRACKED files OUTSIDE `.agent/contracts/` and `.agent/plans/`
  #     are background noise (test scaffolding, editor cruft,
  #     handoff.sh's own lock file) and are IGNORED — neither commit
  #     nor block.
  #   - UNTRACKED files INSIDE `.agent/contracts/` or `.agent/plans/`
  #     that do NOT match the current slice's prefix DO block — those
  #     belong to a different slice and a sibling handoff should commit
  #     them.
  local has_other_dirty=0
  local -a matches=()
  local line code path
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    code="${line:0:2}"
    path="${line:3}"
    if [ "$code" = "??" ]; then
      case "$path" in
        "$contracts_prefix"*|"$plans_prefix"*)
          matches+=("$path")
          ;;
        .agent/contracts/*|.agent/plans/*)
          # Inside contracts/plans but for a DIFFERENT slice — block.
          has_other_dirty=1
          ;;
        *)
          # Outside contracts/plans — ignore (background noise).
          ;;
      esac
    else
      # Tracked modification: ignore if it's the slice's own baton
      # (handoff.sh is allowed to rewrite that). Everything else is
      # "other dirty changes" and disqualifies the auto-commit.
      if [ "$path" != "$baton_path" ]; then
        has_other_dirty=1
      fi
    fi
  done <<< "$porcelain"

  if [ "$has_other_dirty" -eq 1 ]; then
    echo "[handoff] auto-commit SKIPPED: working tree has other dirty changes" >&2
    return 0
  fi
  if [ "${#matches[@]}" -eq 0 ]; then
    echo "[handoff] auto-commit SKIPPED: no untracked slice contracts/plans" >&2
    return 0
  fi

  if ! git -C "$ws_root" add -- "${matches[@]}" >/dev/null 2>&1; then
    echo "[handoff] auto-commit FAILED: git add failed for ${matches[*]}" >&2
    return 0
  fi
  if ! git -C "$ws_root" commit -m "$SLICE: contracts/plans auto-commit (handoff)" >/dev/null 2>&1; then
    echo "[handoff] auto-commit FAILED: git commit failed" >&2
    return 0
  fi
  echo "[handoff] auto-committed: ${matches[*]}"
}

# ─────────────────────────────────────────────────────────────────────────────
# refresh_derived_views: keep the DERIVED index (CURRENT.md) fresh and surface
# baton<->reality drift. Called at the end of BOTH the claim and release paths.
#
# Staleness root cause: batons get updated but CURRENT.md (and any view derived
# from it) lags because nobody re-ran `status.sh index`. Regenerating here makes
# every /handoff refresh the index — and pick up new slices — then flags drift
# (e.g. a job the baton still calls RUNNING that the scheduler has finished).
# status.sh takes no lock, so this is safe to call while handoff holds OWNER.lock.
# Pure/read-only, best-effort — it can NEVER fail the handoff.
# ─────────────────────────────────────────────────────────────────────────────
refresh_derived_views() {
  if [ -f "$ROOT/scripts/status.sh" ]; then
    if bash "$ROOT/scripts/status.sh" index >/dev/null 2>&1; then
      echo "[handoff] CURRENT.md index regenerated"
    else
      echo "[handoff] warning: index regen failed — run ./scripts/status.sh index" >&2
    fi
  fi
  if [ -x "$ROOT/scripts/baton-drift.sh" ]; then
    local _drift
    _drift="$(bash "$ROOT/scripts/baton-drift.sh" 2>/dev/null || true)"
    if [ -n "$_drift" ]; then
      echo "[handoff] ⚠️ baton-drift — fix before the next agent trusts these:" >&2
      printf '%s\n' "$_drift" | sed 's/^/    /' >&2
    fi
  fi
}

# CURRENT.md is required only in no-slice mode (it is the live single-session
# SSOT we bump + snapshot against). In slice mode CURRENT.md is a derived
# index produced later by status.sh, so we do not require it here.
if [ -z "$SLICE" ] && [ ! -f "$CURRENT" ]; then
  echo "[handoff] error: $CURRENT missing. Create it from the template first." >&2
  exit 1
fi

# Acquire the lock for the duration of the snapshot + version bump.
# Prefer `flock` (Linux) for kernel-released semantics; fall back to
# `mkdir`-based mutex (macOS/*BSD) — mkdir is atomic so the loser fails.
if command -v flock >/dev/null 2>&1; then
  exec 200>>"$LOCK_FILE"
  if ! flock -w 30 -x 200; then
    echo "[handoff] error: could not acquire OWNER.lock within 30s — another handoff is running." >&2
    exit 1
  fi
else
  # mkdir-based lock with 30s timeout. atexit cleanup via trap.
  tries=0
  while ! mkdir "$LOCK_DIR" 2>/dev/null; do
    tries=$((tries + 1))
    if [ $tries -ge 30 ]; then
      echo "[handoff] error: could not acquire OWNER.lock.d within 30s — another handoff is running." >&2
      echo "[handoff] If stale, remove '$LOCK_DIR' and retry." >&2
      exit 1
    fi
    sleep 1
  done
  # shellcheck disable=SC2064
  trap "rmdir '$LOCK_DIR' 2>/dev/null || true" EXIT
fi

# ─────────────────────────────────────────────────────────────────────────────
# Release mode: clear owner fields and mark state: released for the slice.
# Separate code path from the claim rewriter: owner_session / owner_label /
# heartbeat are emptied, state is forced to "released", owner_agent /
# remaining_actions / contract_pointers / body are preserved verbatim.
# Idempotent: a second --release on an already-released slice just bumps
# version + last_updated.
# ─────────────────────────────────────────────────────────────────────────────
if [ "$RELEASE_MODE" -eq 1 ]; then
  mkdir -p "$STATUS_DIR"
  slice_file="$STATUS_DIR/$SLICE.md"

  if [ ! -f "$slice_file" ]; then
    echo "[handoff] error: $slice_file missing. Initialize it from the per-slice template first." >&2
    exit 1
  fi

  cur_v="$(awk '
    /^---$/ { in_fm = !in_fm; next }
    in_fm && /^version:/ { print $2; exit }
  ' "$slice_file")"
  cur_v=${cur_v:-0}
  new_v=$((cur_v + 1))

  today="$(date -u +%Y-%m-%d)"

  # Release rewriter: ALL fields in val[] are overwritten in place if
  # present, inserted at the closing --- if absent. owner_agent is NOT in
  # val[] (preserved). state IS in val[] (overwrite mode -> "released").
  tmp="$slice_file.tmp.$$"
  awk \
    -v ver="$new_v" \
    -v upd="$today" '
    BEGIN {
      split("owner_session owner_label heartbeat state version last_updated", order, " ")
      n_fields = 6
      val["owner_session"] = ""
      val["owner_label"]   = ""
      val["heartbeat"]     = ""
      val["state"]         = "released"
      val["version"]       = ver
      val["last_updated"]  = upd
    }
    /^---$/ {
      fm_count++
      if (fm_count == 2) {
        for (i = 1; i <= n_fields; i++) {
          k = order[i]
          if (!(k in seen)) print k ": " val[k]
        }
      }
      print
      next
    }
    fm_count == 1 {
      for (k in val) {
        if ($0 ~ ("^" k ":")) {
          print k ": " val[k]
          seen[k] = 1
          next
        }
      }
    }
    { print }
  ' "$slice_file" > "$tmp"
  mv -f "$tmp" "$slice_file"

  echo "[handoff] released slice=$SLICE version: $cur_v -> $new_v"
  echo "[handoff] wrote: $slice_file"
  slice_auto_commit
  refresh_derived_views
  echo "[handoff] done"
  exit 0
fi

# ─────────────────────────────────────────────────────────────────────────────
# Slice mode: claim/refresh ONLY $STATUS_DIR/<slice>.md and exit.
# Updates exactly 6 frontmatter fields (owner_session, owner_label,
# owner_agent, version, last_updated, heartbeat); preserves remaining_actions,
# contract_pointers, and the whole markdown body verbatim. CURRENT.md is not
# touched (it is a derived index). Lock is held throughout; write is atomic.
# ─────────────────────────────────────────────────────────────────────────────
if [ -n "$SLICE" ]; then
  mkdir -p "$STATUS_DIR"
  slice_file="$STATUS_DIR/$SLICE.md"

  if [ ! -f "$slice_file" ]; then
    echo "[handoff] error: $slice_file missing. Initialize it from the per-slice template first." >&2
    exit 1
  fi

  # owner_session: env OWNER_SESSION, else a generated UUID.
  owner_session="${OWNER_SESSION:-}"
  if [ -z "$owner_session" ]; then
    owner_session="$(uuidgen 2>/dev/null \
      || cat /proc/sys/kernel/random/uuid 2>/dev/null \
      || python3 -c 'import uuid;print(uuid.uuid4())')"
  fi
  owner_label="${OWNER_LABEL:-}"

  # version: current int + 1 (default 0 -> 1), read from this slice file only.
  cur_v="$(awk '
    /^---$/ { in_fm = !in_fm; next }
    in_fm && /^version:/ { print $2; exit }
  ' "$slice_file")"
  cur_v=${cur_v:-0}
  new_v=$((cur_v + 1))

  hb_iso="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  today="$(date -u +%Y-%m-%d)"

  # Replace-in-place if a field line exists in the first frontmatter block;
  # otherwise insert it just before that block's closing ---. The 6
  # owner/version/timestamp fields in val[] are ALWAYS overwritten; `state`
  # is special — preserved verbatim if present, defaulted to "active" only
  # when absent (handoff.sh doesn't flip lifecycle; --release does, Task 3).
  # Every other line (remaining_actions / contract_pointers / body) passes
  # through.
  tmp="$slice_file.tmp.$$"
  awk \
    -v sess="$owner_session" \
    -v label="$owner_label" \
    -v agent="$NEXT_AGENT" \
    -v ver="$new_v" \
    -v upd="$today" \
    -v hb="$hb_iso" '
    BEGIN {
      # Managed fields in stable insertion order. The first 6 are always
      # rewritten in place if present; `state` (7th) is insert-only default.
      split("owner_session owner_label owner_agent version last_updated heartbeat state", order, " ")
      n_fields = 7
      val["owner_session"] = sess
      val["owner_label"]   = label
      val["owner_agent"]   = agent
      val["version"]       = ver
      val["last_updated"]  = upd
      val["heartbeat"]     = hb
      # insert-only default for `state`: used only when the field is absent.
      # An existing `state: <whatever>` line falls through to the default
      # `print` path and is preserved verbatim.
      insert_default["state"] = "active"
    }
    /^---$/ {
      fm_count++
      if (fm_count == 2) {
        # Insert any managed field that was absent from the block, in a
        # stable order, just before the closing ---. For state, use the
        # insert-only default.
        for (i = 1; i <= n_fields; i++) {
          k = order[i]
          if (!(k in seen)) {
            if (k in val) print k ": " val[k]
            else          print k ": " insert_default[k]
          }
        }
      }
      print
      next
    }
    # Inside the first frontmatter block, rewrite a managed field in place.
    # NOTE: only fields in val[] are rewritten; `state` is intentionally
    # NOT in val[], so an existing `state:` line is preserved by the
    # default `print` path below (we still mark it seen so the insert
    # path does not double-add the default).
    fm_count == 1 && /^state:/ {
      seen["state"] = 1
      print
      next
    }
    fm_count == 1 {
      for (k in val) {
        if ($0 ~ ("^" k ":")) {
          print k ": " val[k]
          seen[k] = 1
          next
        }
      }
    }
    { print }
  ' "$slice_file" > "$tmp"
  mv -f "$tmp" "$slice_file"

  echo "[handoff] slice=$SLICE owner_session=$owner_session version: $cur_v -> $new_v heartbeat=$hb_iso"
  echo "[handoff] wrote: $slice_file"
  slice_auto_commit
  refresh_derived_views
  echo "[handoff] done"
  exit 0
fi

stamp_iso="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
stamp_dir="$(date -u +%Y-%m-%d-%H%M%S)"
run_dir="$SESSIONS_DIR/${stamp_dir}-${NEXT_AGENT}"
mkdir -p "$run_dir"
echo "[handoff] next-agent=$NEXT_AGENT at $stamp_iso  →  $(realpath --relative-to="$ROOT" "$run_dir")"

# === Bump version in CURRENT.md frontmatter ===
# Read current version (default 0 if absent).
current_version="$(awk '
  /^---$/ { in_fm=!in_fm; next }
  in_fm && /^version:/ { print $2; exit }
' "$CURRENT")"
current_version=${current_version:-0}
new_version=$((current_version + 1))

# Atomic frontmatter version bump: write to .tmp then mv -f.
tmp="$CURRENT.tmp.$$"
if grep -qE '^version:' "$CURRENT"; then
  awk -v v="$new_version" '
    /^---$/ { fm_count++ }
    fm_count==1 && /^version:/ { print "version: " v; next }
    { print }
  ' "$CURRENT" > "$tmp"
else
  # Insert version: line just before the closing --- of the first frontmatter block.
  awk -v v="$new_version" '
    /^---$/ { fm_count++; if (fm_count==2) { print "version: " v } }
    { print }
  ' "$CURRENT" > "$tmp"
fi
mv -f "$tmp" "$CURRENT"

# === Snapshot git state ===
is_git=0
if git -C "$ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  is_git=1
fi

if [ "$is_git" -eq 1 ]; then
  git -C "$ROOT" status --short                  > "$run_dir/git-status.txt"
  git -C "$ROOT" --no-pager log -n 10 --oneline  > "$run_dir/git-log.txt"
  git -C "$ROOT" --no-pager diff           > "$run_dir/diff.patch"        || true
  git -C "$ROOT" --no-pager diff --cached  > "$run_dir/diff-staged.patch" || true
else
  : > "$run_dir/git-status.txt"
  echo "(workspace is not a git repo: $ROOT)" > "$run_dir/git-log.txt"
  : > "$run_dir/diff.patch"
  : > "$run_dir/diff-staged.patch"
fi

if [ ! -f "$run_dir/session-note.md" ]; then
  cat > "$run_dir/session-note.md" <<'NOTE'
# Session note

Free-form notes from the outgoing agent. Anything that does not fit
in CURRENT.md but the next agent should know.
NOTE
fi

cat > "$run_dir/meta.txt" <<META
generated_at:    $stamp_iso
next_agent:      $NEXT_AGENT
current_version: $new_version
prev_version:    $current_version
root:            $ROOT
host:            $(hostname)
user:            $(id -un)
is_git:          $is_git
META

# Re-point latest -> this run.
ln -sfn "sessions/${stamp_dir}-${NEXT_AGENT}" "$STATE_DIR/latest"

# === Snapshot rotation: keep most recent 20 sessions ===
# Older ones can still be examined manually under .agent/handoffs/state/sessions/.
keep=20
total=$(find "$SESSIONS_DIR" -maxdepth 1 -mindepth 1 -type d | wc -l)
if [ "$total" -gt "$keep" ]; then
  find "$SESSIONS_DIR" -maxdepth 1 -mindepth 1 -type d \
    -printf '%T@ %p\n' 2>/dev/null \
    | sort -n \
    | head -n $((total - keep)) \
    | awk '{ $1=""; sub(/^ +/, ""); print }' \
    | while read -r old; do
        # NB: we are inside our own flock; this prune is safe.
        rm -rf "$old"
      done
fi

# === Stale-CURRENT warning: complain if any <...> placeholders remain ===
if grep -nE '<[^>]+>' "$CURRENT" >/dev/null; then
  echo "[handoff] warning: CURRENT.md still contains <placeholder> fields:" >&2
  grep -nE '<[^>]+>' "$CURRENT" | sed 's/^/  /' >&2
  echo "[handoff] fill them in before ending the session." >&2
fi

echo "[handoff] wrote:"
ls -1 "$run_dir"
echo "[handoff] CURRENT.md version bumped: $current_version -> $new_version"
echo "[handoff] latest -> $(readlink "$STATE_DIR/latest")"
echo
echo "[handoff] next steps for the incoming agent:"
echo "  1. read .agent/handoffs/CURRENT.md (frontmatter + body)"
echo "  2. read .agent/handoffs/takeover-prompt.md if owner_agent != you"
echo "  3. cross-check state/latest/diff.patch and state/latest/git-status.txt"
echo "[handoff] done"

# Lock released on EXIT.
